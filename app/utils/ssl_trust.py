"""Доверенные корни для исходящих HTTPS-запросов.

Python и httpx по умолчанию проверяют сертификаты по набору корней из пакета
certifi — это Mozilla-набор, и системное хранилище они игнорируют. Пока все
контрагенты сидели на международных центрах сертификации, разницы не было.

Российские сервисы переходят на корень Минцифры («Russian Trusted Root CA»),
которого в certifi нет и не будет. Для нас это выглядит как «self-signed
certificate in certificate chain»: цепочка настоящая, но её корню мы не верим.
Так у нас отвалилась выгрузка выписки из банка Точка.

Поэтому проверку ведём по системному хранилищу: администратор ставит нужный
корень штатным update-ca-certificates, и его подхватывают все интеграции разом,
без правок кода и без вкомпиливания чужих сертификатов в репозиторий.

Проверку сертификатов при этом НЕ отключаем ни при каких условиях: это банковские
и налоговые каналы, и выключенная проверка означает, что любой, кто окажется
в середине, читает и подменяет платёжные данные.
"""
import os

# Системные наборы доверенных корней. Первый — Debian/Ubuntu, второй — RHEL.
_SYSTEM_BUNDLES = (
    "/etc/ssl/certs/ca-certificates.crt",
    "/etc/pki/tls/certs/ca-bundle.crt",
)


def ca_bundle():
    """Что передавать в httpx как verify.

    Возвращает путь к системному набору корней, если он есть, иначе True —
    тогда httpx возьмёт certifi (так работает разработка под Windows).

    Путь можно задать явно переменной окружения CA_BUNDLE — например, чтобы
    указать собственный файл, не трогая системный.
    """
    override = os.getenv("CA_BUNDLE", "").strip()
    if override and os.path.exists(override):
        return override
    for path in _SYSTEM_BUNDLES:
        if os.path.exists(path):
            return path
    return True
